export type TranslationKey = keyof typeof en;

export const dictionaries: Record<Lang, Record<TranslationKey, string>> = { en, fr };

export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>) {
  let text: string = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

/** Order-status translator (statuses come from the API in English). */
export function translateStatus(lang: Lang, status: string) {
  const map: Record<string, TranslationKey> = {
    pending: 'status.pending',
    processing: 'status.processing',
    shipped: 'status.shipped',
    delivered: 'status.delivered',
    cancelled: 'status.cancelledWord',
  };
  return map[status] ? translate(lang, map[status]) : status;
}
